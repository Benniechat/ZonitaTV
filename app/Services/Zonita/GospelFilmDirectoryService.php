    /**
     * Ingests, updates, and synchronizes all 60 gospel ministries into the database.
     */
    public function syncDirectory(): array
    {
        $directory = $this->getMasterDirectory();
        $synced = 0;

        foreach ($directory as $entry) {
            $slug = Str::slug($entry['name']);
            GospelFilmProduction::updateOrCreate(
                ['slug' => $slug],
                [
                    'name' => $entry['name'],
                    'founder_or_minister' => $entry['founder_or_minister'] ?? null,
                    'ministry_type' => $entry['ministry_type'] ?? 'drama_ministry',
                    'country_code' => $entry['country_code'] ?? 'NGA',
                    'headquarters_city' => $entry['headquarters_city'] ?? null,
                    'primary_language' => $entry['primary_language'] ?? 'Yoruba with English Subtitles',
                    'sub_genres' => $entry['sub_genres'] ?? [],
                    'youtube_channel_name' => $entry['youtube_channel_name'],
                    'youtube_channel_url' => $entry['youtube_channel_url'],
                    'youtube_handle' => $entry['youtube_handle'] ?? null,
                    'catalogue_size_est' => $entry['catalogue_size_est'] ?? 20,
                    'has_full_length_movies' => $entry['has_full_length_movies'] ?? true,
                    'has_english_subtitles' => $entry['has_english_subtitles'] ?? true,
                    'lead_priority' => $entry['lead_priority'] ?? 3,
                    'sample_feature_titles' => $entry['sample_feature_titles'] ?? [],
                    'licensing_status' => $entry['licensing_status'] ?? 'prospect_identified',
                    'approved_films_count' => $entry['approved_films_count'] ?? 0,
                    'commercial_use_approved' => $entry['commercial_use_approved'] ?? false,
                    'continuous_24_7_approved' => $entry['continuous_24_7_approved'] ?? false,
                    'permitted_territories' => $entry['permitted_territories'] ?? ['GLOBAL', 'NGA'],
                    'notes' => $entry['notes'] ?? null,
                    'last_scanned_at' => now(),
                ]
            );

            $synced++;
        }

        // Deploy or synchronize the African Gospel Film Network Channel
        $channelSync = $this->deployAfricanGospelFilmNetwork();

        return [
            'ministries_synced' => $synced,
            'top_priority_count' => GospelFilmProduction::where('lead_priority', 1)->count(),
            'channel_status' => $channelSync['status'],
            'schedule_entries' => $channelSync['schedule_entries'],
        ];
    }

