    /**
     * Ingests and synchronizes all providers into the persistent database.
     */
    public function syncProviderDirectory(): array
    {
        $directory = $this->getMasterProviderDirectory();
        $synced = 0;

        foreach ($directory as $entry) {
            $slug = Str::slug($entry['name']);
            IslamicContentProvider::updateOrCreate(
                ['slug' => $slug],
                [
                    'name' => $entry['name'],
                    'provider_type' => $entry['provider_type'],
                    'country_code' => $entry['country_code'] ?? 'NGA',
                    'headquarters_city' => $entry['headquarters_city'] ?? null,
                    'primary_language' => $entry['primary_language'] ?? 'Hausa',
                    'supported_subtitles' => $entry['supported_subtitles'] ?? ['English'],
                    'content_categories' => $entry['content_categories'] ?? [],
                    'youtube_channel_name' => $entry['youtube_channel_name'],
                    'youtube_channel_url' => $entry['youtube_channel_url'],
                    'youtube_handle' => $entry['youtube_handle'] ?? null,
                    'official_website' => $entry['official_website'] ?? null,
                    'contact_email' => $entry['contact_email'] ?? null,
                    'catalogue_size_est' => $entry['catalogue_size_est'] ?? 50,
                    'recent_upload_activity' => $entry['recent_upload_activity'] ?? 'weekly',
                    'source_classification' => $entry['source_classification'] ?? 'DISCOVERY_ONLY',
                    'verification_status' => $entry['verification_status'] ?? 'VERIFIED_OWNER',
                    'confidence_score' => $entry['confidence_score'] ?? 85,
                    'licensing_status' => $entry['licensing_status'] ?? 'PROSPECT_IDENTIFIED',
                    'commercial_use_permitted' => $entry['commercial_use_permitted'] ?? false,
                    'continuous_24_7_permitted' => $entry['continuous_24_7_permitted'] ?? false,
                    'permitted_territories' => $entry['permitted_territories'] ?? ['GLOBAL', 'NGA'],
                    'target_channels' => $entry['target_channels'] ?? [],
                    'sample_titles' => $entry['sample_titles'] ?? [],
                    'notes' => $entry['notes'] ?? null,
                    'last_verified_at' => now(),
                ]
            );

            $synced++;
        }

        return [
            'providers_synced' => $synced,
            'verified_owners' => IslamicContentProvider::where('verification_status', 'VERIFIED_OWNER')->count(),
            'active_broadcasting' => IslamicContentProvider::whereIn('licensing_status', ['ACTIVE_BROADCASTING', 'AGREEMENT_SIGNED'])->count(),
        ];
    }
