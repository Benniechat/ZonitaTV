    /**
     * Synchronize all 60 Nollywood channels into the database registry and deploy 24/7 linear channels.
     */
    public function syncDirectory(): array
    {
        $directory = $this->getMasterDirectory();
        $synced = 0;

        foreach ($directory as $entry) {
            $slug = $entry['slug'];
            NollywoodChannel::updateOrCreate(
                ['slug' => $slug],
                [
                    'name' => $entry['name'],
                    'channel_category' => $entry['channel_category'] ?? 'popular_nollywood',
                    'creator_or_lead' => $entry['creator_or_lead'] ?? null,
                    'country_code' => $entry['country_code'] ?? 'NGA',
                    'primary_language' => $entry['primary_language'] ?? 'English',
                    'sub_genres' => $entry['sub_genres'] ?? [],
                    'youtube_channel_name' => $entry['youtube_channel_name'],
                    'youtube_channel_url' => $entry['youtube_channel_url'],
                    'youtube_handle' => $entry['youtube_handle'] ?? null,
                    'website_url' => $entry['website_url'] ?? null,
                    'contact_email' => $entry['contact_email'] ?? null,
                    'contact_phone' => $entry['contact_phone'] ?? null,
                    'catalogue_size_est' => $entry['catalogue_size_est'] ?? 50,
                    'has_full_length_movies' => $entry['has_full_length_movies'] ?? true,
                    'lead_priority' => $entry['lead_priority'] ?? 2,
                    'sample_feature_titles' => $entry['sample_feature_titles'] ?? [],
                    'licensing_status' => $entry['licensing_status'] ?? 'prospect_identified',
                    'approved_films_count' => $entry['approved_films_count'] ?? 0,
                    'commercial_use_approved' => $entry['commercial_use_approved'] ?? false,
                    'continuous_24_7_approved' => $entry['continuous_24_7_approved'] ?? true,
                    'permitted_territories' => $entry['permitted_territories'] ?? ['GLOBAL', 'NGA'],
                    'notes' => $entry['notes'] ?? null,
                    'last_scanned_at' => now(),
                ]
            );

            $synced++;
        }

        // Deploy all 60 Nollywood Channels into the live broadcasting platform
        $channelSync = $this->deployAllNollywoodChannels(7);

        return [
            'channels_synced' => $synced,
            'top_priority_count' => NollywoodChannel::where('lead_priority', 1)->count(),
            'channels_deployed' => $channelSync['channels_deployed'],
            'schedule_entries' => $channelSync['total_schedule_entries'],
        ];
    }

